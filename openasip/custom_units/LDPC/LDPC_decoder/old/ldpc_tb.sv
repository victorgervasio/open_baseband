    // BN Test Runner
    task automatic run_bn_test_vector(
        input bn_test_vector_t test_vec
    );
        logic signed [WIDTH-1:0] q_computed [][];
        logic [MAX_GROUP*MAX_GROUP*WIDTH-1:0] packed_input;
        int group = test_vec.group_size;
        bit test_passed = 1;
        
        // Compute expected outputs using golden model if not pre-computed
        if (test_vec.q_expected[0][0] === 'x) begin
            // Need to compute expected values
            golden_bn_process(group, test_vec.lambda, test_vec.r_input, q_computed);
        end else begin
            // Use pre-computed expected values
            q_computed = new[group];
            foreach (q_computed[j]) q_computed[j] = new[group-1];
            foreach (test_vec.q_expected[j]) begin
                foreach (test_vec.q_expected[j][i]) begin
                    q_computed[j][i] = test_vec.q_expected[j][i];
                end
            end
        end
        
        // Pack input for DUT
        foreach (test_vec.lambda[j]) begin
            packed_input[j*group*WIDTH +: WIDTH] = test_vec.lambda[j];
            foreach (test_vec.r_input[j][i]) begin
                packed_input[j*group*WIDTH + (i+1)*WIDTH +: WIDTH] = test_vec.r_input[j][i];
            end
        end
        
        // Apply stimulus
        u_bn.in_llr = packed_input;
        #10;
        
        // Verify outputs with assertions
        foreach (q_computed[j]) begin
            foreach (q_computed[j][i]) begin
                logic signed [WIDTH-1:0] hw_out;
                hw_out = u_bn.out_llr[(j*(group-1) + i)*WIDTH +: WIDTH];
                
                // Assertion: Hardware output must match golden model
                assert (hw_out === q_computed[j][i]) else begin
                    $error("BN Test %0d (%s): Mismatch at [%0d][%0d] - HW=%0d, Expected=%0d",
                           test_vec.test_id, test_vec.description, j, i, hw_out, q_computed[j][i]);
                    test_passed = 0;
                end
            end
        end
        
        // Update statistics
        total_tests++;
        if (test_passed) begin
            passed_tests++;
