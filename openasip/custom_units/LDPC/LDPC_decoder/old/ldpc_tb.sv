                       test_vec.test_id, test_vec.description, i, hw_out, r_computed[i]);
                test_passed = 0;
            end
        end
        
        // Update statistics
        total_tests++;
        if (test_passed) begin
            passed_tests++;
            $display("[PASS] CN: %s (ID: %08x)", test_vec.description, test_vec.test_id);
        end else begin
