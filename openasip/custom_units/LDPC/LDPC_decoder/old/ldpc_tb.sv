    // Test full LDPC iteration (BN -> CN -> BN)
    task automatic test_full_iteration(
        input int bg,
        input int i_ls,
        input int num_iterations = 1
    );
        int z_c;
        int num_rows = (bg == 1) ? BG1_ROWS : BG2_ROWS;
        int num_cols = (bg == 1) ? BG1_COLS : BG2_COLS;
        
        $display("\n=== Full LDPC Iteration Test: BG%0d, LS%0d ===", bg, i_ls);
        
        // Use for loop instead of foreach
        for (int idx = 0; idx < 8; idx++) begin
            z_c = Z_SETS[i_ls][idx];
            if (z_c == 0) break;
            
            // Create H matrix for this lifting size
            bit H_lifted [num_rows*z_c][num_cols*z_c];
            
            // Build lifted H matrix (simplified - would use V_ij values)
            // For now, use base graph structure
            
            for (int iter = 0; iter < num_iterations; iter++) begin
                $display("  Iteration %0d", iter);
                
                // Initialize Q messages (from BNs to CNs)
                logic signed [WIDTH-1:0] Q [num_rows*z_c][num_cols*z_c];
                logic signed [WIDTH-1:0] R [num_rows*z_c][num_cols*z_c];
                logic signed [WIDTH-1:0] lambda [num_cols*z_c];
                
                // Random initial LLRs
                for (int col = 0; col < num_cols*z_c; col++) begin
                    lambda[col] = random_llr();
                end
                
                // Initialize R messages to zero
                for (int row = 0; row < num_rows*z_c; row++) begin
                    for (int col = 0; col < num_cols*z_c; col++) begin
                        R[row][col] = 8'sd0;
                    end
                end
                
                // BN Processing: Compute Q from lambda and R
                for (int col = 0; col < num_cols*z_c; col++) begin
                    // Find connected CNs for this BN
                    int bn_degree = 0;
                    int connected_cns [];
                    connected_cns = new[num_rows*z_c];
                    
                    for (int row = 0; row < num_rows*z_c; row++) begin
                        if (H_lifted[row][col]) begin
                            connected_cns[bn_degree++] = row;
                        end
                    end
                    
                    // Compute Q for each connected CN
                    for (int i = 0; i < bn_degree; i++) begin
                        int cn_idx = connected_cns[i];
                        logic signed [WIDTH*2-1:0] sum = { {WIDTH{lambda[col][WIDTH-1]}}, lambda[col] };
                        
                        // Sum all R messages except current
                        for (int j = 0; j < bn_degree; j++) begin
                            if (j != i) begin
                                sum += { {WIDTH{R[connected_cns[j]][col][WIDTH-1]}}, R[connected_cns[j]][col] };
                            end
                        end
                        
                        // Saturate
                        if (sum > 127) Q[cn_idx][col] = 127;
                        else if (sum < -128) Q[cn_idx][col] = -128;
                        else Q[cn_idx][col] = sum[WIDTH-1:0];
                    end
                end
                
                // CN Processing: Compute R from Q
                for (int row = 0; row < num_rows*z_c; row++) begin
                    for (int col = 0; col < num_cols*z_c; col++) begin
                        // Find connected BNs for this CN
                        int cn_degree = 0;
                        int connected_bns [];
                        connected_bns = new[num_cols*z_c];
                        
                        for (int c = 0; c < num_cols*z_c; c++) begin
                            if (H_lifted[row][c]) begin
                                connected_bns[cn_degree++] = c;
                            end
                        end
                        
                        if (cn_degree > 0) begin
                            // Find min, second min, and signs
                            logic [WIDTH-1:0] min_val = {WIDTH{1'b1}};
                            logic [WIDTH-1:0] min2_val = {WIDTH{1'b1}};
                            int min_idx = 0;
                            logic total_sign = 1'b0;
                            logic signs [];
                            signs = new[cn_degree];
                            
                            for (int i = 0; i < cn_degree; i++) begin
                                int bn_idx = connected_bns[i];
                                logic [WIDTH-1:0] abs_q = Q[row][bn_idx][WIDTH-1] ? -Q[row][bn_idx] : Q[row][bn_idx];
                                signs[i] = Q[row][bn_idx][WIDTH-1];
                                total_sign ^= signs[i];
                                
                                if (abs_q < min_val) begin
                                    min2_val = min_val;
                                    min_val = abs_q;
                                    min_idx = i;
                                end else if (abs_q < min2_val) begin
                                    min2_val = abs_q;
                                end
                            end
                            
                            // Compute R for each connected BN
                            for (int i = 0; i < cn_degree; i++) begin
                                int bn_idx = connected_bns[i];
                                logic [WIDTH-1:0] mag = (i == min_idx) ? min2_val : min_val;
                                logic sign = total_sign ^ signs[i];
                                R[row][bn_idx] = sign ? -mag : mag;
                            end
                        end
                    end
                end
                
                // Verify parity check: H * (lambda + sum(R))^T should be 0
                // This would require full syndrome calculation
            end
        end
    endtask
    
