    //========================================================================
    // Software Reference Models (Golden Reference)
    //========================================================================
    
    // Golden model for BN processing (matches hardware exactly)
    function automatic void golden_bn_process(
        input int group,
        input logic signed [WIDTH-1:0] lambda [],
        input logic signed [WIDTH-1:0] r_in [][],
        output logic signed [WIDTH-1:0] q_out [][]
    );
        logic signed [WIDTH*2-1:0] total_sum;
        logic signed [WIDTH*2-1:0] sum_excluding;
        const logic [WIDTH*2-1:0] MAX_POS = (1 << WIDTH) - 1;
        const logic [WIDTH*2-1:0] MAX_NEG = (1 << (WIDTH-1));
        
        // Initialize output array
        q_out = new[group];
        foreach (q_out[j]) q_out[j] = new[group-1];
        
        foreach (lambda[j]) begin
            // Accumulate total sum: lambda + all incoming R messages
            total_sum = { {WIDTH{lambda[j][WIDTH-1]}}, lambda[j] };
            
            foreach (r_in[j][i]) begin
                total_sum += { {WIDTH{r_in[j][i][WIDTH-1]}}, r_in[j][i] };
            end
            
            // Generate output for each connected CN (subtract its own R message)
            foreach (r_in[j][i]) begin
                sum_excluding = total_sum - { {WIDTH{r_in[j][i][WIDTH-1]}}, r_in[j][i] };
                
                // Clamp (saturate) to 8-bit signed range
                if (sum_excluding > MAX_POS)
                    q_out[j][i] = MAX_POS[WIDTH-1:0];
                else if (sum_excluding < -MAX_NEG)
                    q_out[j][i] = -MAX_NEG;
                else
                    q_out[j][i] = sum_excluding[WIDTH-1:0];
            end
        end
    endfunction
    
    // Golden model for CN processing (Min-Sum algorithm)
    function automatic void golden_cn_process(
        input int group,
        input logic signed [WIDTH-1:0] q_in [],
        output logic signed [WIDTH-1:0] r_out []
    );
        logic [WIDTH-1:0] abs_vals [];
        logic [WIDTH-1:0] min_val, min2_val;
        int min_idx;
        logic total_sign;
        logic signs [];
        
        // Initialize dynamic arrays
        abs_vals = new[group];
        signs = new[group];
        r_out = new[group];
        
        // Step 1: Compute absolute values and track signs
        foreach (q_in[i]) begin
            abs_vals[i] = q_in[i][WIDTH-1] ? -q_in[i] : q_in[i];
            signs[i] = q_in[i][WIDTH-1];
        end
        
        // Step 2: Find first and second minimum absolute values
        min_val = {WIDTH{1'b1}};  // Maximum possible value
        min2_val = {WIDTH{1'b1}};
        min_idx = 0;
        
        foreach (abs_vals[i]) begin
            if (abs_vals[i] < min_val) begin
                min2_val = min_val;
                min_val = abs_vals[i];
                min_idx = i;
            end else if (abs_vals[i] < min2_val) begin
                min2_val = abs_vals[i];
            end
        end
        
        // Step 3: Compute total sign (XOR of all signs)
        total_sign = 1'b0;
        foreach (signs[i]) begin
            total_sign ^= signs[i];
        end
        
        // Step 4: Generate output R messages
        foreach (q_in[i]) begin
            logic [WIDTH-1:0] mag_out;
            logic sign_out;
            
            // Magnitude: min if index != min_idx, otherwise second min
            mag_out = (i == min_idx) ? min2_val : min_val;
            
            // Sign: total_sign XOR sign of current message (self-cancellation)
            sign_out = total_sign ^ signs[i];
            
            // Combine sign and magnitude
            r_out[i] = sign_out ? -mag_out : mag_out;
        end
    endfunction
    
