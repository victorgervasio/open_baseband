        foreach (r_computed[i]) begin
            logic signed [WIDTH-1:0] hw_out;
            hw_out = u_cn.out_llr[i*WIDTH +: WIDTH];
            
            // Assertion: Hardware output must match golden model
            assert (hw_out === r_computed[i]) else begin
